use super::*;

/// Default `.omnimem/config.toml` body written by `omnimem init` so a fresh
/// `omnimem retrieve "x"` succeeds out-of-the-box. Idempotent: if
/// `config.toml` already exists, init does NOT overwrite it.
///
/// previously `omnimem init` created the repo
/// skeleton but never wrote `[embed]`, so a first-time retrieve
/// errored cryptically. Seeding sensible defaults is the smallest
/// fix that turns the box-fresh path into a working demo.
///
/// under the `bundled-embedder` cargo feature
/// (Path A - `cargo install omnimem-cli --features bundled-embedder`)
/// the seeded default flips to onnx + all-MiniLM-L6-v2. The model
/// downloads on first use and caches under
/// `~/.cache/huggingface/hub`; no Ollama install, no OpenAI key,
/// no manual `omnimem config set embed.provider ...` step. Default
/// builds (no bundled-embedder) keep the legacy Ollama seed so
/// users with a local `ollama serve` keep working unchanged.
#[cfg(feature = "bundled-embedder")]
const DEFAULT_CONFIG_TOML: &str = "\
# Auto-generated by `omnimem init`. Override with `omnimem config set <key> <val>`
# or edit this file. See https://github.com/Uranid/omnimem/blob/main/CONFIGURABLES.md
[embed]
provider = \"onnx\"
model = \"all-MiniLM-L6-v2\"
";

#[cfg(not(feature = "bundled-embedder"))]
const DEFAULT_CONFIG_TOML: &str = "\
# Auto-generated by `omnimem init`. Override with `omnimem config set <key> <val>`
# or edit this file. See https://github.com/Uranid/omnimem/blob/main/CONFIGURABLES.md
[embed]
provider = \"ollama\"
model = \"nomic-embed-text\"
";

/// Human-readable provider tag shown in `omnimem init`'s stdout hint so
/// the operator sees the exact provider their fresh repo will use.
#[cfg(feature = "bundled-embedder")]
const DEFAULT_PROVIDER_DESC: &str = "onnx:all-MiniLM-L6-v2";

#[cfg(not(feature = "bundled-embedder"))]
const DEFAULT_PROVIDER_DESC: &str = "ollama:nomic-embed-text";

#[derive(clap::Args, Debug)]
#[command(after_long_help = "\
Examples:
 omnimem init # create .omnimem/ in the current directory
 omnimem init ~/notes # create ~/notes/.omnimem/
 omnimem -R ~/notes status # verify by reading op_id + head commit
")]
pub(crate) struct Args {
    /// Directory to initialise. Defaults to the current directory.
    pub path: Option<std::path::PathBuf>,
}

pub(crate) fn run(_override: Option<&Path>, args: Args) -> Result<()> {
    let target = args
        .path
        .unwrap_or_else(|| std::env::current_dir().unwrap_or_default());
    let data_dir = target.join(repo::omnimem_DIR);

    if data_dir.exists() {
        bail!(
            "already a omnimem repository at {}\n\
 hint: remove the existing `.omnimem/` if you meant a fresh repo, or run \
 `omnimem status` to inspect it. See docs/RUNBOOK.md#6-mid-commit-crash-recovery \
 for recovery semantics.",
            data_dir.display()
        );
    }
    let (bs, ohs) = repo::create_or_open_stores(&data_dir)?;
    let r = ReadonlyRepo::init(bs, ohs)?;

    // seed `.omnimem/config.toml` with sensible
    // defaults so a fresh `omnimem retrieve` works out-of-the-box (with
    // a local Ollama). Idempotent: if the file already exists (e.g.
    // a parent process pre-seeded it), do NOT overwrite. The data
    // dir was created above, so we know it exists.
    let cfg_path = config::path_of(&data_dir);
    if !cfg_path.exists() {
        // Best-effort: a write failure here is not fatal (the repo
        // skeleton is already on disk), so we print a stderr hint
        // and proceed rather than rolling back the init.
        match std::fs::write(&cfg_path, DEFAULT_CONFIG_TOML) {
            Ok(()) => {
                println!(
                    " seeded config: {} ([embed] {})",
                    cfg_path.display(),
                    DEFAULT_PROVIDER_DESC
                );
            }
            Err(e) => {
                eprintln!(
                    "(warn: failed to seed {}: {e}; run `omnimem config set embed.provider {}` manually)",
                    cfg_path.display(),
                    DEFAULT_PROVIDER_DESC.split(':').next().unwrap_or("ollama")
                );
            }
        }
    }

    seed_anchor_node(&r, &data_dir);

    println!("initialised omnimem repo in {}", data_dir.display());
    println!(" root op: {}", r.op_id());

    // Best-effort: register this repo in ~/.omnimemglobal/repos.toml so
    // `omnimem` without -R can discover it. Silent if ~/.omnimemglobal doesn't
    // exist yet (user hasn't run `omnimem integrate`).
    crate::global::register_repo(&target);

    Ok(())
}

/// Create and initialise `.omnimem/` inside `parent` without printing to stdout.
/// Idempotent: returns Ok(()) if the repo already exists.
/// Used by `omnimem init` (via `run`) and `global::bootstrap` (for ~/.omnimemglobal).
pub(crate) fn init_omnimem_dir(parent: &Path) -> Result<()> {
    let data_dir = parent.join(repo::omnimem_DIR);
    if data_dir.exists() {
        return Ok(());
    }
    let (bs, ohs) = repo::create_or_open_stores(&data_dir)?;
    let r = ReadonlyRepo::init(bs, ohs)?;
    let cfg_path = config::path_of(&data_dir);
    if !cfg_path.exists() {
        let _ = std::fs::write(&cfg_path, DEFAULT_CONFIG_TOML);
    }
    seed_anchor_node(&r, &data_dir);
    Ok(())
}

// The anchor UUID itself lives in `omnimem_core::anchor` so the same
// identity is shared by `omnimem init` (the writer), `omnimem reindex` (the
// skip filter), and `Query`/`Retriever` (the read-time filters).
// Re-export the parsed form locally so the rest of this file reads
// the same way it did before the move.
use omnimem_core::anchor::ANCHOR_NODE_UUID as ANCHOR_NODE_ID;

/// Fixed change-id for the anchor commit so the commit CID is byte-identical
/// across all fresh repos. BUG-56: without this, the anchor commit produced by
/// `omnimem init` differs between publisher and subscriber (different ChangeId
/// random bits), making the subscriber's anchor look like divergent history
/// even for a fresh subscriber who has done no real work.
///
/// The bytes spell out "omnimem/anchor/v1" zero-padded to 16 bytes.
const ANCHOR_CHANGE_ID_BYTES: [u8; 16] = *b"omnimem/anchor/v1\0\0";

/// Fixed commit timestamp for the anchor commit (Unix epoch). Paired with
/// `ANCHOR_CHANGE_ID_BYTES` to make the anchor commit CID deterministic.
const ANCHOR_TIME_MICROS: u64 = 0;

/// Commit a minimal anchor node to a freshly-initialised repo.
/// Non-fatal: store or embed failures are silently swallowed so they
/// never block `omnimem init` or `omnimem integrate`. The node makes the
/// graph non-empty from the first second so commit-history operations
/// (`log`, `blame`, `push`, `pull`) have a shared ancestor to anchor
/// against.
///
/// The anchor is structural only: it has no summary, no content, and
/// is filtered from `omnimem retrieve` / `omnimem query` results by default
/// (see [`omnimem_core::anchor::is_system_node`] and the
/// `include_system(true)` audit opt-in on
/// [`omnimem_core::index::query::Query`] /
/// [`omnimem_core::retrieve::retriever::Retriever`]). The reindex
/// candidate collector also skips it, so it never accumulates a
/// fallback vector that would surface as noise in retrieve.
///
/// The anchor commit is fully deterministic (fixed node-id, change-id,
/// and timestamp) so every `omnimem init` produces the same anchor commit
/// CID. This means the anchor IS an ancestor of any publisher's commit
/// chain that started with `omnimem init`, enabling fast-forward pulls
/// into fresh subscriber repos (BUG-56).
fn seed_anchor_node(repo: &ReadonlyRepo, _data_dir: &std::path::Path) {
    use omnimem_core::id::ChangeId;
    use omnimem_core::repo::CommitOptions;

    let anchor_id = NodeId::parse_uuid(ANCHOR_NODE_ID)
        .expect("ANCHOR_NODE_ID is a valid UUID; this is a compile-time constant");
    let node = Node::new(anchor_id, "Meta");

    let mut tx = repo.start_transaction();
    match tx.add_node(&node) {
        Ok(_) => {}
        Err(_) => return,
    }

    let opts = CommitOptions::new("omnimem init", "seed anchor node")
        .with_time_micros(ANCHOR_TIME_MICROS)
        .with_change_id(ChangeId::from_bytes_raw(ANCHOR_CHANGE_ID_BYTES));
    let _ = tx.commit_opts(opts);
}
